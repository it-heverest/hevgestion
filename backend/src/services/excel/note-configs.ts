export const validateNoteData = (noteType: string, data: any): boolean => {
  if (!data.entete) return false;
  if (!data.sections) return false;
  return true;
};

export const calculateNoteTotals = (
  noteConfig: ConfigurationMapping,
  data: any,
) => {
  const totals: any = {};

  Object.keys(data.sections).forEach((sectionKey) => {
    const section = data.sections[sectionKey];
    const sectionTotal: any = {};

    section.lignes?.forEach((ligne: any) => {
      Object.keys(ligne).forEach((key) => {
        if (
          key !== "// 16px" &&
          key !== "element" &&
          key !== "nature" &&
          key !== "natureContrat"
        ) {
          const value = parseFloat(ligne[key]) || 0;
          sectionTotal[key] = (sectionTotal[key] || 0) + value;
        }
      });
    });

    totals[sectionKey] = sectionTotal;
  });

  return totals;
};

